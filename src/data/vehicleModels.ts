/**
 * ユーザー指定厳格連結ルール：
 * 1. 指定席（全席指定）は指定席車同士で連結（一般との連結不可）
 * 2. なし（一般）はなし（一般）同士で連結
 * 3. 名鉄車でも近鉄車でもJR車でも連結可能
 * 4. 両数は増結・解結（単独走行も可能）
 */
export function canCoupleVehicles(v1: VehicleModelData, v2: VehicleModelData): boolean {
  if (v1.seatType === 'all_reserved' && v2.seatType === 'all_reserved') return true;
  if (v1.seatType === 'none' && v2.seatType === 'none') return true;
  return false;
}

export function getCoupledVehicles(baseModel: VehicleModelData): VehicleModelData[] {
  return VEHICLE_MODELS.filter((v) => canCoupleVehicles(baseModel, v));
}

/**
 * ユーザー指示「さっきのPDFで全席指定と備考に書いてあるものは全席指定で動かしていいからね」
 * 備考またはseatTypeが全席指定の車両モデルを判定
 */
export function isAllReservedVehicleModel(modelOrIdOrNickname: string): boolean {
  if (!modelOrIdOrNickname) return false;
  const target = VEHICLE_MODELS.find(
    (v) =>
      modelOrIdOrNickname.includes(v.model) ||
      (v.nickname && modelOrIdOrNickname.includes(v.nickname)) ||
      v.id === modelOrIdOrNickname
  );
  if (target) {
    return target.seatType === 'all_reserved' || (target.remarks?.includes('全席指定') ?? false);
  }
  // 代表的な全席指定形式のキーワード判定
  const allReservedKeywords = [
    'ミュースカイ', 'ひのとり', 'しまかぜ', 'パノラマDX', '白帯', 'しなの', 'サンダーバード',
    '80000', '50000', '21000', '21020', '22000', '22600', '23000', '26000', '30000',
    '12000', '12400', '12600', '16000', '1000系', '1600系', '2000系', '8800系',
    'キハ8500', '373系', '383系', '683系', '15000系', '54000系', '9000系'
  ];
  return allReservedKeywords.some((kw) => modelOrIdOrNickname.includes(kw));
}


